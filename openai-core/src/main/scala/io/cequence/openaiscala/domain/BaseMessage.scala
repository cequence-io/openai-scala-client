object BaseMessage {
  def getTextContent(message: BaseMessage): Option[String] =
    message match {
      case SystemMessage(content, _)    => Some(content)
      case DeveloperMessage(content, _) => Some(content)
      case UserMessage(content, _)      => Some(content)
      case UserSeqMessage(contents, _) =>
        val content = contents.collect { case TextContent(text) => text }.mkString("\n")
        Some(content)
      case AssistantMessage(content, _, _)             => Some(content)
      case AssistantWebSearchMessage(content, _, _, _) => Some(content)
      case AssistantToolMessage(content, _, _)         => content
      case AssistantFunMessage(content, _, _)          => content
      case ToolMessage(content, _, _)                  => content
      case FunMessage(content, _)                      => Some(content)
      case MessageSpec(_, content, _)                  => Some(content)
      case _: ReasoningMessage                         => None
    }
}
