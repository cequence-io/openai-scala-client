import java.io.File
import java.nio.charset.StandardCharsets
import java.nio.file.Files

import scala.meta._

/**
 * Generates the ZIO-native views of the service traits (since 2.0.0): for a service trait `T`
 * a trait `TZIO` with every method of `T` returning ZIO's own types, plus a delegating
 * implementation `TZIODelegate` over a `T`; for an extension class `C` (an implicit class in
 * an object, e.g. the JSON / failover helpers) an implicit class `CZIO` over `TZIO`.
 *
 * The mapping, by the declared result type:
 *   - `Future[A]` -> `Task[A]` (`ZIO.fromFuture`)
 *   - `AsyncStream[A]` -> `ZStream[Any, Throwable, A]`, `AsyncStream[Bytes]` -> `ZStream[Any,
 *     Throwable, Byte]` (via ws-client-zio - a native ZIO leaf stays native)
 *   - `Future[AsyncStream[A]]` / `Future[Option[AsyncStream[A]]]` -> `Task[...]` of the above
 *   - anything else: unchanged
 *
 * Parameters are copied with their defaults (the generated file copies the source file's
 * imports and extends the same non-service parents, so the default expressions resolve); an
 * implicit `ExecutionContext` parameter is dropped (ZIO provides one); a callback `A =>
 * Future[B]` becomes `A => Task[B]`. Scaladoc and `@deprecated` are copied.
 *
 * Purely syntactic - it reads the source files, so the views never drift from the traits.
 */
object ZioServiceGenerator {

  /** A source to mirror: a service trait, or an implicit class `Object.Class` over one. */
  sealed trait Input {
    def file: File
  }

  final case class ServiceTrait(
    file: File,
    name: String
  ) extends Input

  final case class Extension(
    file: File,
    objectName: String,
    className: String
  ) extends Input

  private val SupportImport =
    "import io.cequence.openaiscala.service.{CloseableServiceZIO, CloseableServiceZIODelegate, ServiceZIO, ZIOConversions}"

  private val Header =
    "// GENERATED by project/ZioServiceGenerator.scala - do not edit; regenerated on every build\n"

  def generate(
    inputs: Seq[Input],
    outDir: File
  ): Seq[File] = {
    val serviceNames = inputs.collect { case ServiceTrait(_, name) => name }.toSet

    val parsed = inputs.map { input =>
      val text = new String(Files.readAllBytes(input.file.toPath), StandardCharsets.UTF_8)
      (input, text, dialects.Scala213(text).parse[Source].get)
    }

    val closeable = closeableServices(parsed.collect {
      case (ServiceTrait(file, name), _, source) =>
        name -> serviceTrait(source, name, file).templ.inits.map(_.tpe.syntax)
    }.toMap)

    parsed.map { case (input, text, source) =>
      val (pkg, imports) = packageAndImports(source)

      val generated = input match {
        case ServiceTrait(file, name) =>
          serviceTraitFile(
            pkg,
            imports,
            serviceTrait(source, name, file),
            text,
            serviceNames,
            closeable(name)
          )

        case Extension(_, objectName, className) =>
          val obj = source.collect {
            case o: Defn.Object if o.name.value == objectName => o
          }.headOption.getOrElse(sys.error(s"object $objectName not found in ${input.file}"))
          val cls = obj.templ.stats.collect {
            case c: Defn.Class if c.name.value == className => c
          }.headOption
            .getOrElse(sys.error(s"class $objectName.$className not found in ${input.file}"))
          extensionFile(pkg, imports, objectName, cls, text, serviceNames)
      }

      val name = input match {
        case ServiceTrait(_, n)          => n + "ZIO"
        case Extension(_, objectName, _) => objectName + "ZIO"
      }
      val dir = new File(outDir, pkg.replace('.', '/'))
      dir.mkdirs()
      val out = new File(dir, name + ".scala")
      val content = Header + s"// source: ${input.file.getName}\n" + generated
      val bytes = content.getBytes(StandardCharsets.UTF_8)
      // rewrite only on change, so incremental compilation stays incremental
      if (!out.exists() || !java.util.Arrays.equals(Files.readAllBytes(out.toPath), bytes))
        Files.write(out.toPath, bytes)
      out
    }
  }

  // ------------------------------------------------------------------------ service traits

  private def serviceTrait(
    source: Source,
    name: String,
    file: File
  ): Defn.Trait =
    source.collect {
      case t: Defn.Trait if t.name.value == name => t
    }.headOption.getOrElse(sys.error(s"trait $name not found in $file"))

  /**
   * The services whose view closes something: those extending `CloseableService`, directly or
   * through a service parent - the chain the generated delegates follow (a view of any other
   * service has a `close` that does nothing, so it gets no `layer`).
   */
  private def closeableServices(parents: Map[String, Seq[String]]): Set[String] = {
    def closes(
      name: String,
      seen: Set[String]
    ): Boolean =
      parents.getOrElse(name, Nil).exists { parent =>
        parent == "CloseableService" || (!seen(parent) && closes(parent, seen + name))
      }

    parents.keySet.filter(closes(_, Set.empty))
  }

  private def serviceTraitFile(
    pkg: String,
    imports: Seq[String],
    defn: Defn.Trait,
    text: String,
    serviceNames: Set[String],
    closeable: Boolean
  ): String = {
    val name = defn.name.value
    val parents = defn.templ.inits.map(_.tpe.syntax)

    val mappedParents = parents.map {
      case p if serviceNames.contains(p) => p + "ZIO"
      case "CloseableService"            => "CloseableServiceZIO"
      case p                             => p
    }
    // every view is a ServiceZIO (its runtime, close) - directly, or through a parent view
    val zioParents =
      if (mappedParents.exists(p => p.endsWith("ZIO")))
        mappedParents
      else
        "ServiceZIO" +: mappedParents
    val delegateParents = parents.collect {
      case p if serviceNames.contains(p) => p + "ZIODelegate"
      case "CloseableService"            => "CloseableServiceZIODelegate"
    }

    val methods = publicDefs(defn.templ.stats).map(m => (m, mapped(m)))

    val traitBody = methods.map { case (m, g) =>
      doc(m.tree, text) + annotations(m.mods) + s"  def ${g.signature(true)}: ${g.resultType}\n"
    }.mkString("\n")

    val delegateBody = methods.map { case (m, g) =>
      s"  override def ${g.signature(false)}: ${g.resultType} =\n    ${g.body("asFuture", "zioRuntime")}\n"
    }.mkString("\n")

    val layer =
      if (closeable)
        s"""
  /**
   * A layer of the ZIO view of the service `create` builds (on acquisition), closed with the
   * layer's scope - e.g. `layer(() => OpenAIServiceFactory())` (a function, not a by-name
   * parameter: ZIO's `provide` macro cannot take a by-name call).
   */
  def layer(create: () => $name): _root_.zio.ZLayer[Any, Throwable, ${name}ZIO] =
    layerFromZIO(_root_.zio.ZIO.attempt(create()))

  /**
   * A layer of the ZIO view of the service the effect `create` builds (on acquisition) - e.g.
   * on an engine from the environment - closed with the layer's scope. A factory that throws
   * inside `create` (even in a pure `map` / `serviceWith`) fails the layer, not a defect.
   */
  def layerFromZIO[R](
    create: _root_.zio.ZIO[R, Throwable, $name]
  ): _root_.zio.ZLayer[R, Throwable, ${name}ZIO] =
    _root_.zio.ZLayer.scoped[R](
      _root_.zio.ZIO.acquireRelease(
        create.absorb.flatMap(service => _root_.zio.ZIO.runtime[Any].map(apply(service)(_)))
      )(_.close)
    )
"""
      else
        ""

    val extendsClause = " extends " + zioParents.mkString(" with ")
    val delegateExtends = (s"${name}ZIO" +: delegateParents).mkString(" with ")

    s"""package $pkg

${(imports :+ SupportImport).mkString("\n")}

/**
 * The ZIO-native view of [[$name]]: the same methods, returning ZIO's own types (`Task`,
 * `ZStream`) - generated from [[$name]]. The Future-based service behind is `asFuture`.
 */
trait ${name}ZIO$extendsClause {

  /** The Future-based service this view delegates to. */
  def asFuture: $name

$traitBody}

/** Implements [[${name}ZIO]] over a [[$name]]. */
trait ${name}ZIODelegate extends $delegateExtends {

  override def asFuture: $name

$delegateBody}

object ${name}ZIO {

  /** The ZIO view of `service`, run on `runtime`. */
  def apply(
    service: $name
  )(
    implicit runtime: _root_.zio.Runtime[Any] = _root_.zio.Runtime.default
  ): ${name}ZIO =
    new ${name}ZIODelegate {
      override val asFuture: $name = service
      override val zioRuntime: _root_.zio.Runtime[Any] = runtime
    }
$layer}
"""
  }

  // ------------------------------------------------------------------------ extension classes

  private def extensionFile(
    pkg: String,
    imports: Seq[String],
    objectName: String,
    cls: Defn.Class,
    text: String,
    serviceNames: Set[String]
  ): String = {
    val className = cls.name.value
    val param = cls.ctor.paramss.flatten.headOption.getOrElse(
      sys.error(s"$objectName.$className takes no service")
    )
    val serviceType = param.decltpe.map(_.syntax).getOrElse(sys.error("untyped service"))
    require(
      serviceNames.contains(serviceType),
      s"$objectName.$className extends $serviceType, which is not a generated service"
    )

    val methods = publicDefs(cls.templ.stats).map(m => (m, mapped(m)))
    val target = s"new $objectName.$className(service.asFuture)"

    val body = methods.map { case (m, g) =>
      doc(m.tree, text) + annotations(m.mods) +
        s"    def ${g.signature(true)}: ${g.resultType} =\n      ${g.body(target, "service.zioRuntime")}\n"
    }.mkString("\n")

    s"""package $pkg

${(imports ++ Seq(s"import $objectName._", SupportImport)).mkString("\n")}

/** The ZIO-native [[$objectName]] helpers - generated from it. */
object ${objectName}ZIO {

  /** [[$objectName.$className]] over a [[${serviceType}ZIO]]. */
  implicit class ${className}ZIO(private val service: ${serviceType}ZIO) {

$body  }
}
"""
  }

  // ------------------------------------------------------------------------ methods

  private final case class Member(
    tree: Tree,
    mods: List[Mod],
    name: String,
    tparams: List[Type.Param],
    paramss: List[List[Term.Param]],
    resultType: Type
  )

  private def publicDefs(stats: List[Stat]): List[Member] =
    stats.collect {
      case d: Decl.Def if isPublic(d.mods) =>
        Member(d, d.mods, d.name.value, d.tparams, d.paramss, d.decltpe)
      case d: Defn.Def if isPublic(d.mods) && d.decltpe.isDefined =>
        Member(d, d.mods, d.name.value, d.tparams, d.paramss, d.decltpe.get)
    }.filterNot(m => m.name == "close" && m.paramss.flatten.isEmpty)

  private def isPublic(mods: List[Mod]): Boolean =
    !mods.exists {
      case _: Mod.Private | _: Mod.Protected | _: Mod.Implicit => true
      case _                                                   => false
    }

  private final case class Generated(
    signature: Boolean => String, // with the parameter defaults or not
    resultType: String,
    body: (String, String) => String // (target, runtime) => the body
  )

  private def mapped(m: Member): Generated = {
    // the parameter lists: an implicit ExecutionContext is dropped (ZIO provides one)
    val clauses = m.paramss.map { clause =>
      val implicitClause = clause.exists(_.mods.exists(_.isInstanceOf[Mod.Implicit]))
      val kept =
        if (implicitClause)
          clause.filterNot(p => p.decltpe.exists(t => simpleName(t) == "ExecutionContext"))
        else
          clause
      (implicitClause, clause, kept)
    }

    def signatureClauses(defaults: Boolean) = clauses.collect {
      case (implicitClause, _, kept) if kept.nonEmpty || !implicitClause =>
        val params = kept.map(p => paramSyntax(p, defaults))
        if (implicitClause)
          params.mkString("(\n    implicit ", ",\n    ", "\n  )")
        else if (params.isEmpty)
          "()"
        else
          params.mkString("(\n    ", ",\n    ", "\n  )")
    }

    def callArgs(runtime: String) = clauses.collect { case (false, clause, _) =>
      clause.map(p => argSyntax(p, runtime)).mkString("(", ", ", ")")
    }.mkString

    val tparams =
      if (m.tparams.isEmpty) ""
      else m.tparams.map(_.syntax).mkString("[", ", ", "]")
    val typeArgs =
      if (m.tparams.isEmpty) ""
      else m.tparams.map(_.name.value).mkString("[", ", ", "]")

    val call = (
      target: String,
      runtime: String
    ) => s"$target.${m.name}$typeArgs${callArgs(runtime)}"
    val droppedEc = clauses.exists { case (_, clause, kept) => clause.size != kept.size }
    val (resultType, body) = result(m.resultType, call, droppedEc)

    Generated(
      defaults => s"${m.name}$tparams${signatureClauses(defaults).mkString}",
      resultType,
      body
    )
  }

  // the parameter as declared, a callback `A => Future[B]` as `A => Task[B]`
  private def paramSyntax(
    p: Term.Param,
    defaults: Boolean
  ): String = {
    val mods = p.mods.filterNot(_.isInstanceOf[Mod.Implicit]).map(_.syntax + " ").mkString
    val tpe = p.decltpe.map(t => futureCallback(t).fold(t.syntax)(_._2)).getOrElse("")
    val default = p.default.filter(_ => defaults).map(d => " = " + d.syntax).getOrElse("")
    s"$mods${p.name.value}: $tpe$default"
  }

  private def argSyntax(
    p: Term.Param,
    runtime: String
  ): String =
    p.decltpe match {
      case Some(Type.Repeated(_)) =>
        s"${p.name.value}: _*"
      case Some(Type.Apply(Type.Name("Option"), List(t))) if futureCallback(t).isDefined =>
        s"${p.name.value}.map(ZIOConversions.callback(_)($runtime))"
      case Some(t) if futureCallback(t).isDefined =>
        s"ZIOConversions.callback(${p.name.value})($runtime)"
      case _ =>
        p.name.value
    }

  // `A => Future[B]` -> the ZIO type `A => Task[B]` (also as an Option)
  private def futureCallback(t: Type): Option[(Type, String)] =
    t match {
      case Type.Function(List(arg), Type.Apply(Type.Name("Future"), List(res))) =>
        Some((t, s"${arg.syntax} => _root_.zio.Task[${res.syntax}]"))
      case Type.Apply(Type.Name("Option"), List(inner)) =>
        futureCallback(inner).map { case (_, zio) => (t, s"Option[$zio]") }
      case _ =>
        None
    }

  // (the ZIO result type, (target, runtime) => the body); an ExecutionContext the call needs
  // comes from ZIO: the one of `ZIO.fromFuture`, the executor's for a stream (inside it)
  private def result(
    tpe: Type,
    call: (String, String) => String,
    droppedEc: Boolean
  ): (String, (String, String) => String) =
    tpe match {
      case Type.Apply(Type.Name("Future"), List(inner)) =>
        stream(inner) match {
          case Some((zioType, conversion)) =>
            (
              s"_root_.zio.Task[$zioType]",
              (
                t,
                r
              ) => s"ZIOConversions.task(implicit ec => ${call(t, r)}).map($conversion)"
            )
          case None =>
            optionStream(inner) match {
              case Some((zioType, conversion)) =>
                (
                  s"_root_.zio.Task[Option[$zioType]]",
                  (
                    t,
                    r
                  ) =>
                    s"ZIOConversions.task(implicit ec => ${call(t, r)}).map(_.map($conversion))"
                )
              case None =>
                (
                  s"_root_.zio.Task[${inner.syntax}]",
                  (
                    t,
                    r
                  ) => s"ZIOConversions.task(implicit ec => ${call(t, r)})"
                )
            }
        }

      case other =>
        stream(other) match {
          case Some((zioType, conversion)) if droppedEc =>
            (
              zioType,
              (
                t,
                r
              ) => s"ZIOConversions.streamWithEc(implicit ec => $conversion(${call(t, r)}))"
            )
          case Some((zioType, conversion)) =>
            (
              zioType,
              (
                t,
                r
              ) => s"$conversion(${call(t, r)})"
            )
          case None if droppedEc =>
            (
              other.syntax,
              (
                t,
                r
              ) => s"ZIOConversions.withEc($r)(implicit ec => ${call(t, r)})"
            )
          case None =>
            (
              other.syntax,
              (
                t,
                r
              ) => call(t, r)
            )
        }
    }

  // AsyncStream[A] -> (the ZStream type, the conversion function)
  private def stream(tpe: Type): Option[(String, String)] =
    tpe match {
      case Type.Apply(Type.Name("AsyncStream"), List(Type.Name("Bytes"))) =>
        Some(("_root_.zio.stream.ZStream[Any, Throwable, Byte]", "ZIOConversions.bytes"))
      case Type.Apply(Type.Name("AsyncStream"), List(element)) =>
        Some(
          (
            s"_root_.zio.stream.ZStream[Any, Throwable, ${element.syntax}]",
            "ZIOConversions.stream"
          )
        )
      case _ =>
        None
    }

  private def optionStream(tpe: Type): Option[(String, String)] =
    tpe match {
      case Type.Apply(Type.Name("Option"), List(inner)) => stream(inner)
      case _                                            => None
    }

  private def simpleName(t: Type): String =
    t match {
      case Type.Name(n)        => n
      case Type.Select(_, n)   => n.value
      case Type.Apply(base, _) => simpleName(base)
      case other               => other.syntax
    }

  // ------------------------------------------------------------------------ source details

  private def packageAndImports(source: Source): (String, Seq[String]) = {
    def walk(
      stats: List[Stat],
      prefix: List[String]
    ): (String, Seq[String]) =
      stats.collectFirst { case p: Pkg => p } match {
        case Some(p) =>
          walk(p.stats, prefix :+ p.ref.syntax)
        case None =>
          (prefix.mkString("."), stats.collect { case i: Import => i.syntax })
      }

    walk(source.stats, Nil)
  }

  // the scaladoc right before a member, if any
  private def doc(
    tree: Tree,
    text: String
  ): String = {
    val start = tree.pos.start
    val before = text.substring(0, start)
    val docEnd = before.lastIndexOf("*/")
    val docStart = before.lastIndexOf("/**")
    if (docStart >= 0 && docEnd > docStart && before.substring(docEnd + 2).trim.isEmpty)
      "  " + text.substring(docStart, docEnd + 2).replace("\n  ", "\n  ") + "\n"
    else
      ""
  }

  private def annotations(mods: List[Mod]): String =
    mods.collect {
      case a: Mod.Annot if a.init.tpe.syntax == "deprecated" => "  " + a.syntax + "\n"
    }.mkString
}
